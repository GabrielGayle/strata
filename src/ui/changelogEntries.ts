// What's changed, newest first: Help › Changelog lists these, and "Show me" lights up
// where each one lives. Every new feature or fix adds an entry at the top (see CLAUDE.md).
import type { Tab, UiState } from '../state/store';

/**
 * Where a change lives on screen. Steps run in this order: show `tab`, set `ui`, open
 * the parameter `group` (or `param`'s group), then click open each name in `path` but
 * the last, then light up the last one. Names are `data-hl` (or `data-testid`) values,
 * never CSS paths, so panels can move without breaking the link. With no `path`, the
 * `param` row, else the `group`, else the `tab` itself is lit.
 */
export interface ChangeTarget {
  tab?: Tab;
  ui?: Partial<UiState>;
  group?: string;
  param?: string;
  path?: string[];
}

export interface ChangeEntry {
  /** Day it shipped, YYYY-MM-DD. */
  date: string;
  /** Pull request number, when there is one. */
  pr?: number;
  kind: 'new' | 'fix';
  title: string;
  /** One or two plain sentences: what it does for you. */
  body: string;
  /** Where to find it, in words ("3D view › Rake"), shown when the control isn't on screen. */
  where: string;
  target?: ChangeTarget;
}

/** Through the 3D view's sidebar: open its tab, then light its panel (or a control inside it). */
const FOLD = { candles: 'candles:main', shelf: 'shelf:main', objects: 'objects:main', materials: 'materials', move: 'move', measure: 'measure' } as const;
const side = (tab: keyof typeof FOLD, ...rest: string[]): ChangeTarget => ({ tab: '3d', path: [`sidebar-tab-${tab}`, `fold-${FOLD[tab]}`, ...rest] });
const candles = (...rest: string[]) => side('candles', ...rest);
const shelf = (...rest: string[]) => side('shelf', ...rest);

